export interface Credit {
  author: string
  license: string
  page: string
}

const credits = creditsJson as Record<string, Credit>

/** Attribution for a photo path like "/images/charyn-1.jpg". */
export function creditFor(src: string): Credit | undefined {
  const slug = src.replace(/^.*\//, '').replace(/\.jpg$/, '')
  return credits[slug]
}

